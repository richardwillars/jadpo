#!/usr/bin/env python3
"""Package a compiler-emitted core artifact and common fixed-case probe harness."""
import argparse, hashlib, json, shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
EXP=ROOT/'experiments/wasm-exp1'
p=argparse.ArgumentParser()
p.add_argument('wasm',type=Path)
p.add_argument('output',type=Path)
p.add_argument('--mutated-wasm',type=Path)
p.add_argument('--name',default='jadpo-wasm-exp1-20260930')
a=p.parse_args()
if not a.wasm.is_file(): raise SystemExit('Compiler artifact missing')
if not (EXP/'host/probe.ts').is_file(): raise SystemExit('Common probe harness not ready')
if a.mutated_wasm and not a.mutated_wasm.is_file(): raise SystemExit('Mutated compiler artifact missing')
a.output.mkdir(parents=True,exist_ok=True)
shutil.copyfile(a.wasm,a.output/'application.wasm')
for name in ['driver.ts','probe.ts']:
    shutil.copyfile(EXP/'host'/name,a.output/name)
shutil.copyfile(EXP/'acceptance.json',a.output/'acceptance.json')
metadata={'artifactSha256':hashlib.sha256(a.wasm.read_bytes()).hexdigest(),'artifactBytes':a.wasm.stat().st_size,'sourceSha256':json.loads((EXP/'acceptance.json').read_text())['source']['sha256'],'abi':1}
imports=''
options='{}'
if a.mutated_wasm:
    shutil.copyfile(a.mutated_wasm,a.output/'mutated.wasm')
    imports='import mutatedModule from "./mutated.wasm";\n'
    options='{mutatedModule}'
    metadata['mutatedArtifactSha256']=hashlib.sha256(a.mutated_wasm.read_bytes()).hexdigest()
worker='''// Generated by the experiment packager; application control flow lives in Wasm.
import module from "./application.wasm";
import {runProbeSuite} from "./probe";
import acceptance from "./acceptance.json";
'''+imports+'''const metadata = '''+json.dumps(metadata)+''';
export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (request.method !== "GET" || url.pathname !== "/report")
      return new Response("Not found", {status:404});
    // No request input selects a principal, query, fixture or application value.
    // This disposable endpoint only executes the frozen synthetic test suite.
    try {
      const report = await runProbeSuite(module, acceptance, '''+options+''');
      return Response.json({metadata, report, host:{colo:request.cf?.colo ?? null}},
        {headers:{"cache-control":"no-store"}});
    } catch {
      return Response.json({metadata, error:"Probe harness failed"}, {status:500});
    }
  }
};
'''
(a.output/'worker.js').write_text(worker)
config={'name':a.name,'main':'worker.js','compatibility_date':'2026-09-30','compatibility_flags':[],'workers_dev':True,'preview_urls':False,'observability':{'enabled':True},'rules':[{'type':'CompiledWasm','globs':['**/*.wasm'],'fallthrough':True}]}
(a.output/'wrangler.jsonc').write_text(json.dumps(config,indent=2)+'\n')
(a.output/'artifact.json').write_text(json.dumps(metadata,indent=2)+'\n')
print(json.dumps({'output':str(a.output),**metadata}))
